export function isLessonSlug(value: string): value is LessonSlug {
  return (LESSON_SLUGS as readonly string[]).includes(value);
}

export function learningLesson(value: string | null | undefined) {
  return LEARNING_LESSONS.find((item) => item.slug === value) ?? LEARNING_LESSONS[0];
}

const pythonParsers = `def numbers(text: str) -> list[int]:\n    return [] if text == "" else [int(value) for value in text.split(",")]\n`;
const javaParsers = `    static int[] numbers(String text) {\n        if (text.isEmpty()) return new int[0];\n        return Arrays.stream(text.split(",")).mapToInt(Integer::parseInt).toArray();\n    }\n`;

