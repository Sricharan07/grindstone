export function sprintDay(day: number) {
  return SPRINT_DAYS[Math.min(28, Math.max(1, day)) - 1];
}

export function activitiesFor(day: SprintDay): SessionActivity[] {
  const lessonHref = day.lessonSlug ? `/learn/${day.lessonSlug}` : `/curriculum?day=${day.day}`;
  const common = {
    recall: day.day === 1
      ? { label: "Orient", minutes: 10, href: lessonHref }
      : { label: "Recall", minutes: 10, href: "/problems?view=reviews" },
    aptitude: { label: "Aptitude", minutes: 20, href: `/session/${day.day}/aptitude` },
    concept: { label: "Learn", minutes: 25, href: lessonHref },
    problems: { label: "Solve", minutes: 45, href: `/problems?view=scheduled&day=${day.day}` },
    lab: { label: "Build", minutes: 40, href: `/session/${day.day}/lab` },
    explain: { label: "Explain", minutes: 10, href: `${lessonHref}?step=explain` },
  };

  if (day.kind === "learn") {
    return [
      { id: `d${day.day}-recall`, ...common.recall, title: day.day === 1 ? "Name what you know and one question to resolve" : "Bring back yesterday's key idea", proof: day.day === 1 ? "One known idea and one question for Luna" : "One answer or re-solve from memory" },
      { id: `d${day.day}-aptitude`, ...common.aptitude, title: day.aptitude, proof: "Timed accuracy plus error review" },
      { id: `d${day.day}-concept`, ...common.concept, title: day.outcome, proof: "Prediction and concept check" },
      { id: `d${day.day}-problems`, ...common.problems, title: day.problems.join(" and "), proof: "Code, tests, complexity, and explanation" },
      { id: `d${day.day}-lab`, ...common.lab, title: day.lab, proof: "Runnable artifact or passing test" },
      { id: `d${day.day}-explain`, ...common.explain, title: "Explain the decision and one edge case", proof: "Teach-back and mistake note" },
    ];
  }

  if (day.kind === "gate") {
    return [
      { id: `d${day.day}-warmup`, label: "Warm up", title: "Recall two known patterns", minutes: 10, proof: "Pattern and invariant named", href: "/problems?view=reviews" },
      { id: `d${day.day}-aptitude`, label: "Aptitude", title: day.aptitude, minutes: 25, proof: "Timed section submitted", href: `/session/${day.day}/aptitude` },
      { id: `d${day.day}-interview`, label: "Interview", title: day.outcome, minutes: 55, proof: "Independent timed evidence", href: `/session/${day.day}/gate` },
      { id: `d${day.day}-lab`, label: "Defend", title: day.lab, minutes: 40, proof: "Gate rubric completed", href: `/session/${day.day}/lab` },
      { id: `d${day.day}-debrief`, label: "Debrief", title: "Name the first wrong assumption", minutes: 20, proof: "Repair plan saved", href: `/progress?gate=${day.day}` },
    ];
  }

  return [
    { id: `d${day.day}-recall`, label: "Retain", title: "Re-solve the weakest assisted task", minutes: 25, proof: "Independent retained result", href: "/problems?view=reviews" },
    { id: `d${day.day}-aptitude`, label: "Review", title: day.aptitude, minutes: 20, proof: "Error log corrected", href: `/session/${day.day}/aptitude` },
    { id: `d${day.day}-repair`, label: "Repair", title: day.outcome, minutes: 25, proof: "Misconception check passed", href: "/progress?view=weaknesses" },
    { id: `d${day.day}-resolve`, label: "Re-solve", title: "Complete one fresh related problem", minutes: 35, proof: "No-help submission", href: "/problems?view=reviews" },
    { id: `d${day.day}-lab`, label: "Polish", title: day.lab, minutes: 35, proof: "Tests and artifact improved", href: `/session/${day.day}/lab` },
    { id: `d${day.day}-plan`, label: "Plan", title: day.kind === "final" ? "Commit the next 28-day plan" : `Prepare Week ${Math.min(4, day.week + 1)}`, minutes: 10, proof: day.evidence, href: "/progress" },
  ];
}
